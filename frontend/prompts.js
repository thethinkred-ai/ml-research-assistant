/* prompts.js — промпты двух слоёв:
   1) Write — развёртывание разделов в связный текст (SYSTEM);
   2) исследовательские режимы (рецензия п. 3, 10, 12): Explore, Verify, Compare,
      Critic, марксистская экспертиза — доказательная база прежде красивого текста. */
(function (global, factory) {
  var api = factory(global);
  if (typeof module === "object" && module.exports) module.exports = api;
  if (global) global.MLPrompts = api;
})(typeof globalThis !== "undefined" ? globalThis : (typeof self !== "undefined" ? self : this), function (global) {
  "use strict";

  var SYSTEM =
    "Ты — научный редактор, пишущий учебные и научные работы по методике В. С. Безруковой " +
    "(реферат, курсовая, дипломная). Методологическая позиция — ортодоксальный марксизм-ленинизм: " +
    "диалектический и исторический материализм; категории базиса и надстройки, противоречия как источника " +
    "развития, перехода количества в качество, отрицания отрицания, единства исторического и логического, " +
    "восхождения от абстрактного к конкретному; практика как критерий истины и цель познания; классовый и " +
    "формационный анализ там, где он уместен. Пиши по-русски, строго научным стилем, без идеалистических и " +
    "эклектичных формулировок, опираясь на материальную обусловленность явлений. Не выдумывай точных цитат и " +
    "библиографических данных — помечай места для ссылок как [источник]. Не утверждай научную новизну от себя: " +
    "новизна заявляется только с основанием, заданным в фактах. Верни только текст раздела, без пояснений от себя.";

  // Отдельный системный промпт для аналитических режимов (не «пиши текст», а «думай и проверяй»).
  var MODE_SYSTEM =
    "Ты — методолог-исследователь (марксизм-ленинизм: диалектический и исторический материализм, практика " +
    "как критерий истины). Твоя задача — не писать красивый текст, а работать с доказательной базой: " +
    "различать факты, определения, интерпретации, причинные и количественные утверждения; отделять " +
    "подтверждённое от непроверенного; не выдумывать источники и данные — непроверенное помечай [источник]. " +
    "Отвечай по-русски, строго, структурированно.";

  function facts(bp) {
    return [
      "Тема: " + bp.meta.topic,
      "Тип работы: " + bp.kindLabel + " (" + bp.researchTypeLabel + "); область: " + (bp.meta.field || "общая"),
      "Объект: " + bp.object,
      "Предмет: " + bp.subject,
      "Цель: " + bp.goal,
      "Задачи: " + bp.tasks.join(" "),
      bp.hypothesis ? ("Гипотеза: " + bp.hypothesis) : "",
      "Исследовательские вопросы (черновик): " + bp.questions.join(" "),
      bp.noveltyReady ? ("Заявляемая новизна (с основанием автора): " + bp.novelty) : "",
      "Методы: " + bp.methods.theoretical.concat(bp.methods.empirical).join("; ")
    ].filter(Boolean).join("\n");
  }

  // Возвращает список задач развёртывания: [{key,title,prompt}]
  function buildTasks(bp, words) {
    words = words || 320;
    var tasks = [];
    tasks.push({
      key: "intro", title: "Введение",
      prompt: "Напиши раздел «Введение» объёмом ~" + words + " слов. Включи: актуальность, противоречие, " +
        "проблему, объект, предмет, цель, задачи, гипотезу (если есть), методы, методологическую основу, " +
        "структуру работы. Используй факты ниже как основу, но разверни их в связный научный текст. " +
        "Начинай сразу с текста, без заголовка и без пояснений от себя.\n\n" + facts(bp)
    });
    bp.structure.chapters.forEach(function (c, ci) {
      c.sub.forEach(function (s, si) {
        tasks.push({
          key: "ch" + (ci + 1) + "_" + (si + 1), title: s,
          prompt: "Напиши параграф «" + s + "» (~" + words + " слов) как часть «" + c.title + "». " +
            "Держись марксистско-ленинской методологии, раскрывай противоречия и материальную обусловленность. " +
            "Не изобретай фактических данных; эмпирические величины помечай [источник]. " +
            "Начинай сразу с текста параграфа, без заголовка и без пояснений от себя.\n\n" + facts(bp)
        });
      });
    });
    tasks.push({
      key: "concl", title: "Заключение",
      prompt: "Напиши «Заключение» (~" + Math.round(words * 0.7) + " слов): краткие итоги по каждой задаче, " +
        "подтверждение/уточнение гипотезы, практическая значимость (" + bp.significance +
        "), перспективы исследования. " +
        (bp.noveltyReady
          ? "Новизна заявлена с основанием — изложи её: " + bp.novelty + " "
          : "Научную новизну не утверждай — вместо этого укажи, какие результаты работы претендуют на новизну и какое основание нужно, чтобы её заявить. ") +
        "Начинай сразу с текста, без заголовка.\n\n" + facts(bp)
    });
    return tasks;
  }

  // ---------- исследовательские режимы ----------

  // Explore: карта темы до всякого письма (рецензия п. 3).
  function explorePrompt(bp) {
    return "Исследуй тему (режим Explore). Дай структурированную карту:\n" +
      "1) основные понятия и что требует уточнения определений;\n" +
      "2) школы и подходы — кто и что утверждает, в чём расходятся;\n" +
      "3) спорные вопросы и нерешённые проблемы;\n" +
      "4) ключевые источники — только реально существующие, непроверенное помечай [источник];\n" +
      "5) противоречия и материальные условия (марксистский анализ);\n" +
      "6) пробелы — что не исследовано и может стать углом данной работы.\n" +
      "Формат: нумерованные разделы, кратко, без воды. В конце — 3–5 исследовательских вопросов, " +
      "которые стоит добавить к черновым.\n\n" + facts(bp);
  }

  // Verify: проверка конкретного утверждения (рецензия п. 4).
  function verifyPrompt(claim) {
    return "Проверь утверждение (режим Verify):\n\nУТВЕРЖДЕНИЕ: " + claim.text +
      "\nТИП: " + claim.type + "\n\nФормат ответа строго такой:\n" +
      "1. РЕЗЮМЕ ПРОВЕРКИ: подтверждается / частично подтверждается / не подтверждается / нехватка данных.\n" +
      "2. КАКИЕ ИСТОЧНИКИ МОГЛИ БЫ ПОДТВЕРДИТЬ: только реально существующие (автор, название, год); " +
      "если не уверен в существовании — пометь [источник].\n" +
      "3. КАКИЕ ДАННЫЕ НУЖНЫ: что именно искать (статистика, архив, эксперимент).\n" +
      "4. СЛАБЫЕ МЕСТА: что в формулировке утверждения уязвимо (кванторы, причинность, подмена понятий).\n" +
      "5. РЕКОМЕНДАЦИЯ: какой тип источника и какой метод проверки закроют утверждение.\n" +
      "Не выдумывай цитаты, страницы и выходные данные.";
  }

  // Compare: структурированная матрица сопоставления (рецензия п. 3).
  function comparePrompt(bp, authors) {
    var who = authors && authors.trim() ? authors.trim() :
      "Маркс, виднейший немарксистский автор XX века и один современный исследователь";
    return "Сравни подходы к теме (режим Compare): " + who + ".\n" +
      "Не пиши связный текст — построй матрицу сравнения:\n\n" +
      "| Критерий | Подход 1 | Подход 2 | Подход 3 |\n" +
      "|---|---|---|---|\n" +
      "| Ключевая категория | … | … | … |\n" +
      "| Единица анализа | … | … | … |\n" +
      "| Объяснение «" + bp.meta.topic + "» | … | … | … |\n" +
      "| Что считает причиной | … | … | … |\n" +
      "| Сильная сторона | … | … | … |\n" +
      "| Слепое пятно | … | … | … |\n\n" +
      "После матрицы: 3–5 строк — где позиции несовместимы принципиально и какой эксперимент/источник " +
      "мог бы разрешить спор. Категории держи марксистскими, где это уместно; непроверяемое помечай [источник].\n\n" +
      facts(bp);
  }

  // Critic: разбор готового текста по таксономии ошибок (рецензия п. 10).
  var CRITIC_TAXONOMY =
    "— утверждение без источника;\n" +
    "— источник не подтверждает утверждение;\n" +
    "— логический скачок («следовательно» без основания);\n" +
    "— смешение корреляции и причинности;\n" +
    "— чрезмерный квантор («всегда», «все», «впервые»);\n" +
    "— подмена понятия (категория употреблена в другом смысле);\n" +
    "— круговое объяснение;\n" +
    "— противоречие между задачей и выводом;\n" +
    "— вывод выходит за пределы данных.";

  function critiquePrompt(text, bp) {
    return "Проведи критику текста (режим Critic). Ищи конкретные ошибки, а не давай общие советы:\n" +
      CRITIC_TAXONOMY + "\n\n" +
      "Формат ответа: таблица «Цитата из текста | Тип ошибки | Почему это ошибка | Как исправить». " +
      "Если ошибок нет в какой-то категории — не выдумывай. В конце: итог (сколько утверждений без " +
      "основания, какие два исправления важнее всего).\n\nТЕКСТ ДЛЯ КРИТИКИ:\n\n" + text +
      (bp ? "\n\nКОНТЕКСТ ИССЛЕДОВАНИЯ:\n" + facts(bp) : "");
  }

  // Марксистская экспертиза: категориальная проверка употребления понятий (рецензия п. 12).
  function marxistAuditPrompt(text, bp) {
    return "Проведи марксистскую категориальную экспертизу текста (режим «экспертиза»):\n" +
      "1) Выпиши все значимые экономические/философские категории, употреблённые в тексте.\n" +
      "2) Для каждой: корректно ли употребление с позиций трудовой теории стоимости и " +
      "исторического материализма; если нет — какая подмена или эклектика допущена и как правильно.\n" +
      "3) Проверь причинные утверждения: связываются ли явления через материальные условия " +
      "(отношения собственности, характер труда, классовые интересы), а не через идеи или намерения.\n" +
      "4) Классические основания (Маркс, Энгельс, Ленин) указывай только там, где уверен в существовании " +
      "пассажа; иначе помечай [источник].\n" +
      "5) Итог: какие 2–3 формулировки текста нужно переформулировать в первую очередь и как.\n\n" +
      "ТЕКСТ:\n\n" + text + (bp ? "\n\nКОНТЕКСТ:\n" + facts(bp) : "");
  }

  return {
    SYSTEM: SYSTEM, MODE_SYSTEM: MODE_SYSTEM, CRITIC_TAXONOMY: CRITIC_TAXONOMY,
    buildTasks: buildTasks, facts: facts,
    explorePrompt: explorePrompt, verifyPrompt: verifyPrompt, comparePrompt: comparePrompt,
    critiquePrompt: critiquePrompt, marxistAuditPrompt: marxistAuditPrompt
  };
});
