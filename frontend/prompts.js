/* prompts.js — построение промптов для развёртывания разделов
   в связный текст с методологией ортодоксального марксизма-ленинизма. */
(function (global, factory) {
  var api = factory(global);
  if (typeof module === "object" && module.exports) module.exports = api;
  if (global) global.MLPrompts = api;
})(typeof globalThis !== "undefined" ? globalThis : (typeof self !== "undefined" ? self : this), function (global) {
  "use strict";

  var SYSTEM =
    "Ты — научный редактор, пишущий учебные и научные работы по методике В. С. Безруковой " +
    "(реферат, курсовая, дипломная). Методологическая позиция — ортодоксальный марксизм-ленинизм: " +
    "диалектический и исторический материализм; категории базиса и надстройки, противоречия как источника " +
    "развития, перехода количества в качество, отрицания отрицания, единства исторического и логического, " +
    "восхождения от абстрактного к конкретному; практика как критерий истины и цель познания; классовый и " +
    "формационный анализ там, где он уместен. Пиши по-русски, строго научным стилем, без идеалистических и " +
    "эклектичных формулировок, опираясь на материальную обусловленность явлений. Не выдумывай точных цитат и " +
    "библиографических данных — помечай места для ссылок как [источник]. Верни только текст раздела, без " +
    "пояснений от себя.";

  function facts(bp) {
    return [
      "Тема: " + bp.meta.topic,
      "Тип работы: " + bp.kindLabel + "; область: " + bp.meta.field,
      "Объект: " + bp.object,
      "Предмет: " + bp.subject,
      "Цель: " + bp.goal,
      "Задачи: " + bp.tasks.join(" "),
      bp.hypothesis ? ("Гипотеза: " + bp.hypothesis) : "",
      "Методы: " + bp.methods.theoretical.concat(bp.methods.empirical).join("; ")
    ].filter(Boolean).join("\n");
  }

  // Возвращает список задач развёртывания: [{key,title,prompt}]
  function buildTasks(bp, words) {
    words = words || 320;
    var tasks = [];
    tasks.push({
      key: "intro", title: "Введение",
      prompt: "Напиши раздел «Введение» объёмом ~" + words + " слов. Включи: актуальность, противоречие, " +
        "проблему, объект, предмет, цель, задачи, гипотезу (если есть), методы, методологическую основу, " +
        "структуру работы. Используй факты ниже как основу, но разверни их в связный научный текст. " +
        "Начинай сразу с текста, без заголовка и без пояснений от себя.\n\n" + facts(bp)
    });
    bp.structure.chapters.forEach(function (c, ci) {
      c.sub.forEach(function (s, si) {
        tasks.push({
          key: "ch" + (ci + 1) + "_" + (si + 1), title: s,
          prompt: "Напиши параграф «" + s + "» (~" + words + " слов) как часть «" + c.title + "». " +
            "Держись марксистско-ленинской методологии, раскрывай противоречия и материальную обусловленность. " +
            "Не изобретай фактических данных; эмпирические величины помечай [источник]. " +
            "Начинай сразу с текста параграфа, без заголовка и без пояснений от себя.\n\n" + facts(bp)
        });
      });
    });
    tasks.push({
      key: "concl", title: "Заключение",
      prompt: "Напиши «Заключение» (~" + Math.round(words * 0.7) + " слов): краткие итоги по каждой задаче, " +
        "подтверждение/уточнение гипотезы, научная новизна (" + bp.novelty + "), практическая значимость (" +
        bp.significance + "), перспективы исследования. Начинай сразу с текста, без заголовка.\n\n" + facts(bp)
    });
    return tasks;
  }

  return { SYSTEM: SYSTEM, buildTasks: buildTasks, facts: facts };
});
