  // Проверка формулировки темы по правилам книги: соответствие объёму работы (не слишком
  // широка, не перегружена). Детерминированная эвристика без сети.
  function analyzeTopic(m) {
    var topic = m.topic.replace(/^«|»$/g, "").trim();
    var words = topic.split(/\s+/).filter(Boolean);
    var res = { verdict: "ok", message: "", suggestions: [] };
    if (!topic || topic === "[укажите тему]") {
      res.verdict = "empty"; res.message = "Тема не задана.";
      return res;
    }
    if (words.length <= 2) {
      res.verdict = "wide";
      res.message = "Формулировка, видимо, шире, чем позволяет объём работы (~" + m.volumePages + " с.)";
      res.suggestions = [
        "добавьте ограничивающий аспект: «" + topic + " в условиях…», «" + topic + " как фактор…»;",
        "сузьте масштаб: период, отрасль, регион, социальная группа;",
        "привяжите к предметной области: «" + topic + "» в контексте " + m.field + "."
      ];
      return res;
    }
    if (words.length >= 10) {
      res.verdict = "narrow";
      res.message = "Формулировка перегружена — такую тему трудно удержать в рамках одной работы";
      res.suggestions = [
        "выделите ядро темы (5–8 слов), остальное вынесите в задачи и параграфы;",
        "проверьте, нельзя ли убрать уточнения, не меняя смысла проблемы."
      ];
      return res;
    }
    res.message = "формулировка соответствует объёму работы; проверьте лишь ключевые термины";
    return res;
  }

