  // Ориентировочный объём (слов) одного раздела при LLM-развёртывании: ~180 слов на страницу,
  // поровну между секциями; ограничен 120–500. Умножается на коэффициент «глубины» в UI.
  function suggestWords(bp) {
    var n = 1 + bp.structure.chapters.reduce(function (a, c) { return a + c.sub.length; }, 0) + 1;
    var w = Math.round((bp.meta.volumePages * 180) / n);
    return Math.max(120, Math.min(500, w));
  }

  function buildBlueprint(raw) {
    var m = norm(raw);
    m.chaptersLabel = m.kind === "referat" ? "двух глав" : (m.kind === "kursovaya" ? "двух глав" : "трёх глав");
    var p = presetFor(m.field);
    var r = rng(m.topic + "|" + m.kind);
    var bp = {
      meta: m,
      preset: p.key,
      kindLabel: KINDS[m.kind].label,
      researchTypeLabel: RESEARCH_TYPES[m.researchType].label,
      contradiction: contradiction(m, r),
      contradictionReady: contradictionReady(m),
      researchSituation: {
        required: m.rsRequired, obstacle: m.rsObstacle, gap: m.rsGap,
        strong: m.strongSide, weak: m.weakSide
      },
      actualnost: actualnost(m, p, r),
      problem: problem(m, r),
      object: "", subject: "",
      goal: goal(m, r),
      tasks: tasks(m, p),
      hypothesis: hypothesis(m),
      hypothesisReady: !!(m.hypX && m.hypY),
      questions: researchQuestions(m),
      methods: methods(m, p),
      stages: stages(m),
      novelty: noveltyBlock(m),
      noveltyReady: noveltyReady(m),
      significance: significance(m, p),
      structure: structure(m)
    };
    var os = objectSubject(m, p); bp.object = os.object; bp.subject = os.subject;
    bp.intro = introTemplate(m, bp);
    bp.concl = conclTemplate(m, bp);
    bp.topicCheck = analyzeTopic(m);
    bp.apparatusCheck = checkApparatus(bp);
    bp.literature = literature(m);
    bp.literatureLinks = literatureLinks(m);
    return bp;
  }

