  function methods(m, p) {
    var theor = p.methods.concat([
      "диалектический метод (единство и борьба противоположностей; переход количества в качество; отрицание отрицания)",
      "историко-материалистический анализ (базис и надстройка, формационный и классовый подходы)",
      "единство исторического и логического",
      "восхождение от абстрактного к конкретному",
      "анализ и синтез, индукция и дедукция, абстрагирование, идеализация, формализация, моделирование"
    ]);
    var emp = m.hasEmpirical
      ? p.evidence.map(function (e) { return "работа с источниками данных: " + e; }).concat([
         "наблюдение", "измерение", "констатирующий и формирующий эксперимент", "анкетирование", "беседа/интервью",
         "экспертные оценки", "методы математической статистики (обработка результатов)"])
      : p.evidence.concat(["изучение и обобщение научно-методической литературы", "анализ документов и нормативных материалов"]);
    return { theoretical: theor, empirical: emp };
  }

